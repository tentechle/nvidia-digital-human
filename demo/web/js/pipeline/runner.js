// Runs one conversational turn through the stages and reports what happens.
//
// Two answer modes:
//   scripted  the reply comes from conversation/replies.js, then a speaker says it
//   llm       the question goes to the live server, whose LLM answers and speaks
//             (only when the active speaker supports it)
//
// Emits on the bus:
//   turn:start { turn, question }   turn:end { turn, stopped }
//   stage { id, state }             state: idle | active | done | skipped
//   trace { turn, t, stage, msg }   t: seconds since the turn started
//   expression <name>
//   reply { text, mood, topic }                 scripted answer, all at once
//   reply:start, reply:chunk { text }           LLM answer, as it is spoken
import { STAGES } from "./stages.js";
import { splitSentences } from "../voice/voice.js";

const STOPPED = Symbol("stopped");

export function createRunner({ bus, answer, getSpeaker, getAnswerMode = () => "scripted" }) {
  let turn = 0;
  let running = false;
  let stopped = false;
  let speaker = null;

  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const check = () => { if (stopped) throw STOPPED; };
  const words = (text) => text.split(/\s+/).filter(Boolean).length;

  async function run(question) {
    if (running) return;
    running = true;
    stopped = false;
    speaker = getSpeaker();
    const useLlm = getAnswerMode() === "llm" && speaker.canChat;
    const id = ++turn;
    const t0 = performance.now();
    const trace = (stage, msg) => bus.emit("trace", { turn: id, t: (performance.now() - t0) / 1000, stage, msg });
    const stage = (sid, state) => bus.emit("stage", { id: sid, state });
    const speaking = (secs, note) => {
      ["a2f", "render", "stream"].forEach((s) => stage(s, "active"));
      trace("tts", `first audio after ${secs.toFixed(2)} s${note ? ` (${note})` : ""}`);
      if (speaker.kind === "live") trace("a2f", "mouth frames generated by wav2lip on the server GPU");
      else trace("a2f", "jaw and lip weights follow the speech; brows and smile follow the mood");
    };

    bus.emit("turn:start", { turn: id, question });
    STAGES.forEach((s) => stage(s.id, "idle"));
    try {
      stage("asr", "skipped");
      trace("asr", "typed input, no audio to transcribe");
      stage("llm", "active");
      bus.emit("expression", "thinking");

      if (useLlm) {
        trace("llm", `question sent to the ${speaker.label}'s LLM`);
        bus.emit("reply:start");
        stage("tts", "active");
        const result = await speaker.chat(question, {
          onFirstAudio: (secs) => {
            stage("llm", "done");
            bus.emit("expression", "neutral");
            speaking(secs, "LLM + speech synthesis on the server");
          },
          onSentence: (text) => {
            trace("tts", `"${text}"`);
            bus.emit("reply:chunk", { text });
          },
          onError: (err) => trace("llm", `request failed: ${err.message}`),
          onNote: (msg) => trace("stream", msg),
        });
        check();
        if (result.timedOut) trace("llm", "no answer within 30 s: check the server log and NVIDIA_API_KEY");
        else trace("llm", `answer: ${words(result.text)} words`);
      } else {
        trace("llm", "matching the question to a scripted reply");
        await sleep(700);
        check();
        const reply = answer(question);
        trace("llm", `reply ready: topic "${reply.topic}", ${words(reply.text)} words`);
        stage("llm", "done");

        stage("tts", "active");
        trace("tts", `${splitSentences(reply.text).length} sentences, ${speaker.describe()}`);
        bus.emit("reply", reply);
        bus.emit("expression", reply.mood);
        await speaker.say(reply.text, {
          onFirstAudio: (secs) => speaking(secs),
          onSentence: (text) => trace("tts", `"${text}"`),
          onError: (err) => trace("tts", `request failed: ${err.message}`),
          onNote: (msg) => trace("stream", msg),
        });
        check();
      }

      ["llm", "tts", "a2f", "render", "stream"].forEach((s) => stage(s, "done"));
      trace("stream", `turn finished in ${((performance.now() - t0) / 1000).toFixed(1)} s`);
    } catch (err) {
      if (err !== STOPPED) throw err;
      STAGES.forEach((s) => stage(s.id, "idle"));
      trace("stream", "stopped");
    } finally {
      running = false;
      bus.emit("turn:end", { turn: id, stopped });
    }
  }

  function stop() {
    if (!running) return;
    stopped = true;
    speaker?.stop();
  }

  return { run, stop, isRunning: () => running };
}
